def single_batch_overfit(
    context: StudyContext,
    rows: npt.NDArray[np.int64],
    arm: str,
    steps: int,
) -> tuple[float, float, int]:
    planner = Planner(PlannerConfig(arm=arm))
    planner.train(True)
    optimizer = build_optimizer(planner.bundle.scorer.parameters(), (), OptimConfig(learning_rate=1e-2))
    labels = derived_targets(context.encoded, rows, context.attributes)
    band_target = torch.as_tensor(context.encoded.band_target[rows], dtype=torch.long)
    tier_target = torch.as_tensor(context.encoded.tier_target[rows], dtype=torch.long)
    severity_target = torch.as_tensor(context.encoded.severity_target[rows], dtype=torch.long)
    risk_target = torch.as_tensor(context.encoded.risk_target[rows], dtype=torch.float32)
    losses: list[float] = []
    for step in range(steps):
        features = build_features(context.encoded, rows, planner, train_encoder=False)
        if step == 0:
            planner.bundle.scorer.fit_normalisation(features)
            features = build_features(context.encoded, rows, planner, train_encoder=False)
        output = planner.bundle.scorer(features)
        objective, _breakdown = compose(
            output.band_logits,
            output.tier_logits,
            output.severity_logits,
            output.risk_logit,
            band_target,
            tier_target,
            severity_target,
            risk_target,
            ObjectiveWeights(),
            derived_band=labels[0],
            derived_tier=labels[1],
            graded_severity=labels[2],
            evidence_complete=labels[3],
        )
        losses.append(float(objective.detach()))
        optimizer.zero_grad(set_to_none=True)
        backpropagate(objective)
        optimizer.step()
    return (losses[0], losses[-1], steps)


