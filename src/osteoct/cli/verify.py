@dataclass
class CheckResult:
    identifier: str
    category: str
    description: str
    status: str
    detail: str = ""
    evidence: dict[str, object] = field(default_factory=dict)

    def record(self) -> dict[str, object]:
        return {
            "id": self.identifier,
            "category": self.category,
            "description": self.description,
            "status": self.status,
            "detail": self.detail,
            "evidence": self.evidence,
        }


class Check:
    def __init__(self, identifier: str, category: str, description: str) -> None:
        self.identifier = identifier
        self.category = category
        self.description = description

    def ok(self, evidence: dict[str, object] | None = None) -> CheckResult:
        return CheckResult(self.identifier, self.category, self.description, PASS, "", evidence or {})

    def bad(self, detail: str, evidence: dict[str, object] | None = None) -> CheckResult:
        return CheckResult(self.identifier, self.category, self.description, FAIL, detail, evidence or {})

    def skip(self, detail: str, evidence: dict[str, object] | None = None) -> CheckResult:
        return CheckResult(self.identifier, self.category, self.description, NOT_RUN, detail, evidence or {})

    def blocked(self, detail: str, evidence: dict[str, object] | None = None) -> CheckResult:
        return CheckResult(self.identifier, self.category, self.description, BLOCKED, detail, evidence or {})


