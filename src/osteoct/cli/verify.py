def reference_auc(scores: npt.NDArray[np.float64], labels: npt.NDArray[np.int64]) -> float:
    positives = np.asarray(scores, dtype=np.float64)[labels == 1]
    negatives = np.asarray(scores, dtype=np.float64)[labels == 0]
    if positives.size == 0 or negatives.size == 0:
        return float("nan")
    wins = 0.0
    for positive in positives.tolist():
        for negative in negatives.tolist():
            if positive > negative:
                wins += 1.0
            elif positive == negative:
                wins += 0.5
    ratio: float = wins / (positives.size * negatives.size)
    return ratio


def reference_sensitivity_at_specificity(
    scores: npt.NDArray[np.float64],
    labels: npt.NDArray[np.int64],
    target: float,
) -> float:
    candidates = sorted({float(value) for value in np.asarray(scores, dtype=np.float64).tolist()})
    best = 0.0
    for threshold in candidates:
        predictions = np.asarray(scores, dtype=np.float64) >= threshold
        positives = labels == 1
        negatives = labels == 0
        sensitivity = float(predictions[positives].sum() / max(1, int(positives.sum())))
        specificity = float(1.0 - predictions[negatives].sum() / max(1, int(negatives.sum())))
        if specificity >= target - 1e-12:
            best = max(best, sensitivity)
    return best


def reference_concordance(
    times: npt.NDArray[np.float64],
    events: npt.NDArray[np.bool_],
    scores: npt.NDArray[np.float64],
) -> float:
    total = 0
    concordant = 0.0
    for first in range(times.size):
        for second in range(first + 1, times.size):
            if times[first] == times[second]:
                continue
            earlier, later = (first, second) if times[first] < times[second] else (second, first)
            if not events[earlier]:
                continue
            total += 1
            if scores[earlier] > scores[later]:
                concordant += 1.0
            elif scores[earlier] == scores[later]:
                concordant += 0.5
    if total == 0:
        return float("nan")
    return concordant / total


def reference_glcm_pairs(quantised: npt.NDArray[np.int32], offset: tuple[int, int, int]) -> list[tuple[int, int]]:
    shape = (int(quantised.shape[0]), int(quantised.shape[1]), int(quantised.shape[2]))
    pairs: list[tuple[int, int]] = []
    for x in range(shape[0]):
        for y in range(shape[1]):
            for z in range(shape[2]):
                source = (x + offset[0], y + offset[1], z + offset[2])
                if 0 <= source[0] < shape[0] and 0 <= source[1] < shape[1] and 0 <= source[2] < shape[2]:
                    pairs.append((int(quantised[x, y, z]), int(quantised[source])))
    return pairs


def reference_glcm_contrast(pairs: Sequence[tuple[int, int]], levels: int) -> float:
    counts = np.zeros((levels, levels), dtype=np.float64)
    for first, second in pairs:
        counts[first, second] += 1.0
        counts[second, first] += 1.0
    total = counts.sum()
    if total <= 0:
        return 0.0
    matrix = counts / total
    value = 0.0
    for row in range(levels):
        for column in range(levels):
            value += matrix[row, column] * float((row - column) ** 2)
    return value


def reference_run_counts(values: Sequence[int]) -> list[tuple[int, int]]:
    runs: list[tuple[int, int]] = []
    if not values:
        return runs
    start = 0
    for index in range(1, len(values) + 1):
        if index == len(values) or values[index] != values[start]:
            runs.append((int(values[start]), index - start))
            start = index
    return runs


def reference_haar_energy(signal: Sequence[float]) -> tuple[float, float]:
    values = np.asarray(signal, dtype=np.float64)
    if values.size % 2 == 1:
        values = np.concatenate([values, values[-1:]])
    scale = 1.0 / np.sqrt(2.0)
    low = (values[0::2] + values[1::2]) * scale
    high = (values[0::2] - values[1::2]) * scale
    return (float(np.mean(low**2)), float(np.mean(high**2)))


def reference_icc(first: npt.NDArray[np.float64], second: npt.NDArray[np.float64]) -> float:
    subjects = first.size
    if subjects < 2:
        return 0.0
    grand = float(np.mean(np.concatenate([first, second])))
    subject_means = (first + second) / 2.0
    rater_means = (float(np.sum(first)) / subjects, float(np.sum(second)) / subjects)
    between = 0.0
    for index in range(subjects):
        between += 2.0 * (float(subject_means[index]) - grand) ** 2
    between /= subjects - 1
    within = 0.0
    for index in range(subjects):
        for rater, value in enumerate((float(first[index]), float(second[index]))):
            residual = value - float(subject_means[index]) - rater_means[rater] + grand
            within += residual**2
    within /= subjects - 1
    if between + within <= 0.0:
        return 1.0
    return float((between - within) / (between + within))


def reference_holm(p_values: Sequence[float]) -> list[float]:
    values = list(p_values)
    count = len(values)
    order = sorted(range(count), key=lambda index: values[index])
    adjusted = [0.0] * count
    running = 0.0
    for rank, index in enumerate(order):
        candidate = values[index] * (count - rank)
        running = max(running, candidate)
        adjusted[index] = min(1.0, running)
    return adjusted


def reference_kappa(first: Sequence[int], second: Sequence[int]) -> float:
    labels = sorted(set(first) | set(second))
    size = len(first)
    table: dict[tuple[int, int], int] = {}
    for left, right in zip(first, second, strict=True):
        table[(left, right)] = table.get((left, right), 0) + 1
    observed = sum(count for (left, right), count in table.items() if left == right) / size
    expected = 0.0
    for label in labels:
        row = sum(count for (left, _), count in table.items() if left == label) / size
        column = sum(count for (_, right), count in table.items() if right == label) / size
        expected += row * column
    return float((observed - expected) / (1.0 - expected))


def reference_net_benefit(
    probabilities: npt.NDArray[np.float64],
    outcomes: npt.NDArray[np.float64],
    threshold: float,
) -> float:
    size = outcomes.size
    flagged = 0
    true_positive = 0
    for probability, outcome in zip(probabilities.tolist(), outcomes.tolist(), strict=True):
        if probability >= threshold:
            flagged += 1
            if outcome > 0.5:
                true_positive += 1
    false_positive = flagged - true_positive
    odds = threshold / (1.0 - threshold)
    return float(true_positive / size - false_positive / size * odds)


def reference_conformance(
    active: Sequence[FamilyName],
    violated: Sequence[FamilyName],
) -> float:
    total = sum(FAMILY_WEIGHTS.values())
    satisfied = sum(weight for family, weight in FAMILY_WEIGHTS.items() if family in set(active) and family not in set(violated))
