def reference_band(
    standard_attenuation_hu: float,
    uncertainty_hu: float,
    calibration: BandCalibration,
    prior_fracture: bool,
) -> tuple[DiagnosticBand, ...]:
    low_threshold, high_threshold = calibration.thresholds_hu()
    lower = standard_attenuation_hu - uncertainty_hu
    upper = standard_attenuation_hu + uncertainty_hu
    compatible: list[DiagnosticBand] = []
    if upper >= high_threshold:
        compatible.append(DiagnosticBand.NORMAL)
    if lower <= high_threshold and upper >= low_threshold:
        compatible.append(DiagnosticBand.OSTEOPENIA)
    if lower <= low_threshold:
        compatible.append(DiagnosticBand.OSTEOPOROSIS)
        compatible.append(DiagnosticBand.SEVERE_OSTEOPOROSIS)
    del prior_fracture
    return tuple(compatible)


def reference_grade(height_loss: float, thresholds: GenantThresholds) -> DeformityGrade:
    if height_loss + thresholds.boundary_tolerance < thresholds.fracture_floor:
        return DeformityGrade.NONE
    if height_loss + thresholds.boundary_tolerance < thresholds.moderate_floor:
        return DeformityGrade.MILD
    if height_loss + thresholds.boundary_tolerance < thresholds.severe_floor:
        return DeformityGrade.MODERATE
    return DeformityGrade.SEVERE


def reference_tier(
    band: DiagnosticBand,
    prior_fracture: bool,
    treatment_exposure: bool,
    risk_semantics_bound: bool,
    in_envelope: bool,
) -> RiskTier:
    order = [RiskTier.LOW, RiskTier.MODERATE, RiskTier.HIGH, RiskTier.VERY_HIGH]
    base = {
        DiagnosticBand.NORMAL: 0,
        DiagnosticBand.OSTEOPENIA: 1,
        DiagnosticBand.OSTEOPOROSIS: 2,
        DiagnosticBand.SEVERE_OSTEOPOROSIS: 3,
    }[band]
    if prior_fracture:
        base = min(3, base + 1)
    if treatment_exposure and not prior_fracture:
        base = max(0, base - 1)
    if not risk_semantics_bound:
        base = max(0, base - 1)
    if not in_envelope:
        base = max(0, base - 1)
    return order[base]


