def resolve_anchor(package_dir: Path, path: str, symbol: str) -> bool:
    target = package_dir / path
    if not target.is_file():
        return False
    source = target.read_text(encoding="utf-8")
    if "." in symbol:
        owner, member = symbol.split(".", 1)
        if f"class {owner}" not in source and f"def {owner}" not in source:
            return False
        return (f"def {member}" in source) or (f"{member}:" in source) or (f"{member} =" in source)
    return (f"def {symbol}" in source) or (f"class {symbol}" in source) or (f"{symbol}:" in source) or (f"{symbol} =" in source)


def write_claim_map(root: Path, package_dir: Path) -> dict[str, object]:
    claims: list[dict[str, object]] = []
    anchors = 0
    resolved = 0
    unresolved: list[str] = []
    for entry in CLAIMS:
        code_entries: list[dict[str, object]] = []
        raw_anchors = entry.get("code")
        assert isinstance(raw_anchors, (list, tuple))
        anchors_for_claim: tuple[tuple[str, str], ...] = tuple((str(pair[0]), str(pair[1])) for pair in raw_anchors)
        for path, symbol in anchors_for_claim:
            anchors += 1
            found = resolve_anchor(package_dir, str(path), str(symbol))
            resolved += int(found)
            if not found:
                unresolved.append(f"{entry['id']}:{path}:{symbol}")
            code_entries.append({"path": str(path), "symbol": str(symbol), "resolved": found})
        claims.append(
            {
                "id": entry["id"],
                "paper_location": entry["paper_location"],
                "claim": entry["claim"],
                "code": code_entries,
                "verification": "EXECUTED" if all(item["resolved"] for item in code_entries) else "UNRESOLVED",
            }
        )
    payload: dict[str, object] = {
        "artifact": "paper-claim to code mapping",
        "release": "Ontology-Guided Opportunistic CT Agent for Early Osteoporosis Prognosis Using Vertebral Attenuation, Trabecular Texture, and Fracture-Risk Semantics",
        "venue": "IEEE Journal of Biomedical and Health Informatics",
        "package_dir": package_dir.name,
        "anchor_convention": "code[].path is relative to package_dir; code[].symbol is a module-level name, or Class.member for a method",
        "verification_vocabulary": VERIFICATION_VOCABULARY,
        "counts": {"claims": len(claims), "anchors": anchors, "resolved_anchors": resolved, "unresolved": unresolved},
        "claims": claims,
        "deviations": DEVIATIONS,
    }
    atomic_write_json(root / "claim_to_code.json", payload)
    return payload


